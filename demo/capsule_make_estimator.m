function estimator = capsule_make_estimator(name, config, pilot, rho, domain, varargin)
    % CAPSULE_MAKE_ESTIMATOR Construct one paper estimator with explicit gain units.
    %   RHO is DD-domain noise variance for MDDIPIC and DRAP. It is not the
    %   time-domain variance passed to TD OMP/NOMP by capsule_run_case.
    %   Optional controls are used only by the computational ablation.

    % SPDX-License-Identifier: GPL-3.0-only
    % Copyright (c) 2026 Koorosh Ahmadi. See COPYRIGHT.txt.
    % Additional MATLAB permission: LICENSES/MATLAB_EXCEPTION.txt.
    % Attribution and paper citation: CITATION.md.

    parser = inputParser;
    parser.addParameter('Schur', true, @(x) islogical(x) && isscalar(x));
    parser.addParameter('Cache', true, @(x) islogical(x) && isscalar(x));
    parser.addParameter('Cycles', 1, @(x) isnumeric(x) && isscalar(x) && x >= 1);
    parser.parse(varargin{:});
    options = parser.Results;
    d = config.demo;
    shared = {'M', config.waveform.M, 'N', config.waveform.N, ...
              'Na', config.array.Nr, 'fs', config.waveform.fs_Hz, ...
              'x_dd', pilot, 'padtype', 'NONE', 'padlen', 0};
    joint = [shared, {'tau_grid_coarse', d.tauGrid, 'nu_grid_coarse', d.nuGrid, ...
                      'theta_grid_coarse', d.angleGrid, 'theta_grid_fine', d.fineAngleGrid, ...
                      'm_tau', d.shrinkFactor, 'n_nu', d.shrinkFactor, ...
                      'max_iter_fine', d.refinementLevels, 'P_max', d.maximumOrder, ...
                      'rho', rho, 'AutoStopRule', 'peakdrop', ...
                      'PeakDropThreshold_dB', d.peakDrop_dB, 'stop_scale', d.residualScale}];
    sparse = [shared, {'tau_grid_coarse', d.tauGrid, 'nu_grid_coarse', d.nuGrid, ...
                       'P_max', d.maximumOrder, 'FineDelayPoints', 0, ...
                       'FineDopplerPoints', 0, 'NormalizeProjection', true, ...
                       'JointGainUpdate', false}];

    switch string(name)
        case "MDDIPIC"
            estimator = MDDIPICEstimator(joint{:}, ...
                                         'UseSchurScoreUpdate', options.Schur, ...
                                         'EnableDDResponseCache', options.Cache);
        case "DRAP"
            estimator = DRAPMDDIPICEstimator(joint{:}, ...
                                             'NumAlternatingRefinements', options.Cycles, ...
                                             'EnableDDResponseCache', options.Cache);
        case "DDAFR"
            estimator = DDAFRBenchmarkEstimator(sparse{:}, ...
                                                'theta_grid_coarse', d.angleGrid, 'theta_grid_fine', d.fineAngleGrid);
        case "MDDAFR"
            estimator = MDDAFRBenchmarkEstimator(sparse{:}, ...
                                                 'theta_grid_fine', d.fineAngleGrid, 'music_theta_grid', d.fineAngleGrid);
        case "OMP"
            % Fourfold refinement reproduces the paper's OMP grid policy.
            dense = @(grid) linspace(grid(1), grid(end), 4 * (numel(grid) - 1) + 1);
            args = [shared, {'tau_grid', dense(d.tauGrid), 'nu_grid', dense(d.nuGrid), ...
                             'theta_grid', dense(d.angleGrid), 'P_max', d.maximumOrder, ...
                             'NormalizeSelection', true}];
            if string(domain) == "sensing"
                estimator = Classic3DOMPSensingEstimator(args{:});
            else
                estimator = SrivastavaOMPBenchmarkEstimator(args{:});
            end
        case "NOMP"
            estimator = Li3DNOMPCommonHostEstimator(shared{:}, ...
                                                    'tau_grid', d.tauGrid, 'nu_coarse_grid', d.nuGrid, ...
                                                    'theta_coarse_grid', d.angleGrid, 'P_max', d.maximumOrder, ...
                                                    'Rs', 4, 'Rc', 5, 'RhoNu', 4, 'RhoTheta', 4, ...
                                                    'AtomConvention', 'project', 'EnableFractionalDelayRefinement', true);
        otherwise
            error('MDDIPIC:Method', 'Unknown estimator: %s', name);
    end
end
